fi

step() { printf '\n%s==> %s%s\n' "$C_BOLD" "$1" "$C_OFF"; }
info() { printf '    %s\n' "$1"; }
ok() { printf '    %s✓%s %s\n' "$C_GREEN" "$C_OFF" "$1"; }
warn() { printf '    %s!%s %s\n' "$C_YELLOW" "$C_OFF" "$1"; }
fail() { printf '\n%sBłąd:%s %s\n' "$C_RED" "$C_OFF" "$1" >&2; exit 1; }

# Questions read the terminal even when the script itself came through a pipe.
TTY_IN="${MELLIS_TTY_IN:-/dev/stdin}"
if [ -z "${MELLIS_TTY_IN:-}" ] && [ ! -t 0 ] && (: </dev/tty) 2>/dev/null; then TTY_IN="/dev/tty"; fi

# ask "Question" "default" [indent] -> REPLY
ask() {
  local prompt="$1" default="${2:-}" indent="${3-    }"
  if [ -n "$default" ]; then
    printf '%s%s %s[%s]%s: ' "$indent" "$prompt" "$C_DIM" "$default" "$C_OFF"
  else
    printf '%s%s: ' "$indent" "$prompt"
  fi
  REPLY=""
  # One descriptor for the whole run: answers are read in order (also from a file, in the tests).
  if [ -z "${TTY_FD_OPEN:-}" ]; then exec 3<"$TTY_IN"; TTY_FD_OPEN=1; fi
  if ! IFS= read -r REPLY <&3; then
    [ -n "$REPLY" ] || { printf '\n'; fail "brak odpowiedzi (koniec wejścia)."; }
  fi
  if [ -z "$REPLY" ]; then REPLY="$default"; fi
}

# confirm "Question" Y|N -> 0 for yes
confirm() {
  local prompt="$1" default="${2:-Y}" hint="T/n"
  if [ "$default" = "N" ]; then hint="t/N"; fi
  while true; do
    ask "$prompt ($hint)" ""
    case "$REPLY" in
      "") [ "$default" = "Y" ]; return ;;
      t|T|tak|Tak|y|Y|yes) return 0 ;;
      n|N|nie|Nie|no) return 1 ;;
      *) info "Wpisz t (tak) albo n (nie)." ;;
    esac
  done
}

# The medical-safety acknowledgement, shown before anything is built (docs-site/docs/instalacja/aplikacja.md).
