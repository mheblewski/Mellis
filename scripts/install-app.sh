# A server address as typed: https:// added when missing, no query, no trailing slash. Empty when it is not one.
# http:// only in a Debug build (a local test server); a Release app refuses it.
normalize_server_url() {
  python3 -I -c '
import sys, urllib.parse
text, allow_http = sys.argv[1].strip(), sys.argv[2] == "1"
if "://" not in text:
    text = "https://" + text
parts = urllib.parse.urlsplit(text)
scheme = parts.scheme.lower()
host = parts.hostname or ""
# A host name with a dot (or localhost / an IP address): a configuration code pasted here is not one.
if not host or ("." not in host and ":" not in host and host != "localhost"):
    sys.exit(1)
if scheme not in ("https", "http") or (scheme == "http" and not allow_http) or " " in text:
    sys.exit(1)
print(urllib.parse.urlunsplit((scheme, parts.netloc.lower(), parts.path.rstrip("/"), "", "")))
' "$1" "$( [ "$OPT_CONFIGURATION" = "Debug" ] && echo 1 || echo 0 )"
}

# A link carrying a code: mellis://pair?server=…&code=… (anywhere in the text), or an https link with ?code=… (its
# server= parameter, else its own origin). Prints "server<TAB>code"; exit 1 when the text holds no such link.
parse_pairing_link() {
  python3 -I -c '
import re, sys, urllib.parse
text = sys.argv[1].strip()
match = re.search(r"mellis://\S+", text, re.I) or re.search(r"https?://\S+", text, re.I)
if not match:
    sys.exit(1)
parts = urllib.parse.urlsplit(match.group(0))
query = {k.lower(): v[0].strip() for k, v in urllib.parse.parse_qs(parts.query).items() if v}
code = query.get("code", "")
if not code:
    sys.exit(1)
if parts.scheme.lower() == "mellis":
    if (parts.hostname or "").lower() != "pair":
        sys.exit(1)
    server = query.get("server", "")
else:
    server = query.get("server") or urllib.parse.urlunsplit((parts.scheme, parts.netloc, "", "", ""))
if not server:
    sys.exit(1)
print(server + "\t" + code)
' "$1"
}

# The server reads codes ignoring case, spaces and dashes, O as 0 and I/L as 1 (Crockford base32). Prints the code in
# groups of five (7KQ2M-9XH4T-3BWRZ-8QJ5N); exit 1 when it cannot be a Mellis code.
normalize_code() {
  local code
  code="$(printf '%s' "$1" | tr '[:lower:]' '[:upper:]' | tr -d ' \t-' | tr 'OIL' '011')"
  printf '%s' "$code" | grep -Eq '^[0-9A-HJKMNP-TV-Z]{16,40}$' || return 1
  printf '%s\n' "$code" | sed -E 's/(.{5})/\1-/g; s/-$//'
}

# curl_json METHOD URL [body] [setup code] -> HTTP_BODY and HTTP_STATUS (000 when unreachable). Not in a $(…): the
# globals must reach the caller.
HTTP_STATUS=""
HTTP_BODY=""
curl_json() {
  local method="$1" url="$2" body="${3:-}" setup_code="${4:-}" out status
  out="$(mktemp "${TMPDIR:-/tmp}/mellis-http.XXXXXX")"
  local args=(-sS --max-time 15 -o "$out" -w '%{http_code}' -X "$method" -H 'Accept: application/json')
  if [ -n "$setup_code" ]; then args+=(-H "X-Mellis-Setup-Code: ${setup_code}"); fi
  if [ -n "$body" ]; then args+=(-H 'Content-Type: application/json' --data-binary "$body"); fi
  status="$(curl "${args[@]}" "$url" 2>/dev/null)" || status="000"
  HTTP_STATUS="${status:-000}"
  HTTP_BODY="$(cat "$out" 2>/dev/null)"
  rm -f "$out"
}

# GET /v1/app-config (version) and GET /v1/setup (device mode, whether the owner's phone is connected).
check_server() {
  local config setup
  SERVER_STATE="UNREACHABLE"; SERVER_VERSION=""
  curl_json GET "${SERVER_URL}/v1/app-config"; config="$HTTP_BODY"
  if [ "$HTTP_STATUS" = "200" ]; then
    SERVER_VERSION="$(printf '%s' "$config" | json_get server.version || true)"
    # Only X.Y.Z picks a release tag (the server's answer is not trusted as a git ref).
    [[ "$SERVER_VERSION" =~ ^v?[0-9]+\.[0-9]+\.[0-9]+$ ]] || SERVER_VERSION=""
  fi
  curl_json GET "${SERVER_URL}/v1/setup"; setup="$HTTP_BODY"
  case "$HTTP_STATUS" in
    200)
      case "$(printf '%s' "$setup" | json_get setup || true)" in
        OPEN) SERVER_STATE="OPEN" ;;
        COMPLETED) SERVER_STATE="COMPLETED" ;;
        *) SERVER_STATE="NOT_DEVICE" ;;
      esac
      ;;
    000) SERVER_STATE="UNREACHABLE" ;;
    *) SERVER_STATE="NOT_DEVICE" ;;
  esac
}

# Whether the code is the server's SETUP_CODE (GET /v1/setup lists the patients only for it) or a pairing code.
classify_code() {
  local answer
  CODE_KIND="pairing"
  if [ "$SERVER_STATE" = "OPEN" ]; then
    curl_json GET "${SERVER_URL}/v1/setup" "" "$PAIRING_CODE"; answer="$HTTP_BODY"
    if [ "$HTTP_STATUS" = "200" ] && printf '%s' "$answer" | json_get patients >/dev/null; then CODE_KIND="setup"; fi
  fi
}

# Takes "Adres serwera" (or a whole pairing link, which carries both) -> SERVER_URL [+ PAIRING_CODE].
read_server_answer() {
  local text="$1" parsed server code url
  if parsed="$(parse_pairing_link "$text")"; then
    server="$(printf '%s' "$parsed" | cut -f1)"; code="$(printf '%s' "$parsed" | cut -f2)"
    url="$(normalize_server_url "$server")" || return 1
    code="$(normalize_code "$code")" || return 1
    SERVER_URL="$url"; PAIRING_CODE="$code"; CODE_FROM_LINK=1
    return 0
  fi
  url="$(normalize_server_url "$text")" || return 1
  SERVER_URL="$url"
}

# Takes "Kod konfiguracji": the code (7KQ2M-9XH4T-3BWRZ-8QJ5N, any case, with or without dashes) or a whole link of
# this server -> PAIRING_CODE. Exit 1: not a code; exit 2: a link of another server.
read_code_answer() {
  local text="$1" parsed server code url
  if parsed="$(parse_pairing_link "$text")"; then
    server="$(printf '%s' "$parsed" | cut -f1)"; code="$(printf '%s' "$parsed" | cut -f2)"
    url="$(normalize_server_url "$server")" || return 1
    [ "$url" = "$SERVER_URL" ] || return 2
    code="$(normalize_code "$code")" || return 1
    PAIRING_CODE="$code"
    return 0
  fi
  code="$(normalize_code "$text")" || return 1
  PAIRING_CODE="$code"
}

configure_server() {
  step "Serwer"
  local status
  if [ -n "$OPT_SERVER" ]; then
    read_server_answer "$OPT_SERVER" || fail "--server: to nie jest adres serwera (https://…)."
  else
    while true; do
      ask "Adres serwera" "$SERVER_URL"
      if [ -z "$REPLY" ]; then warn "Adres jest w notatce \"Mellis\" (np. https://mellis.example.pl)."; continue; fi
      if read_server_answer "$REPLY"; then break; fi
      if [ "$OPT_CONFIGURATION" = "Release" ] && printf '%s' "$REPLY" | grep -qi '^[[:space:]]*http://'; then
        warn "Adres musi zaczynać się od https:// (http:// tylko przy testach z --debug)."
      else
        warn "To nie wygląda na adres serwera (np. https://mellis.example.pl)."
      fi
    done
  fi
  if [ -n "$OPT_CODE" ]; then
    read_code_answer "$OPT_CODE"; status=$?
    case "$status" in
      0) CODE_FROM_FLAG=1 ;;
      2) fail "--code: link jest z innego serwera niż ${SERVER_URL}." ;;
      *) fail "--code: to nie jest kod konfiguracji (np. 7KQ2M-9XH4T-3BWRZ-8QJ5N)." ;;
    esac
  fi
  if [ "$CODE_FROM_LINK" = "1" ]; then CODE_FROM_FLAG=1; fi

  check_server
  case "$SERVER_STATE" in
    OPEN) ok "serwer ${SERVER_URL}${SERVER_VERSION:+ · wersja ${SERVER_VERSION}} · czeka na telefon właściciela" ;;
    COMPLETED) ok "serwer ${SERVER_URL}${SERVER_VERSION:+ · wersja ${SERVER_VERSION}}" ;;
    NOT_DEVICE)
      warn "${SERVER_URL} odpowiada, ale to nie jest serwer Mellis do łączenia telefonów (brak /v1/setup)."
      confirm "Mimo to zbudować aplikację?" N || fail "sprawdź adres serwera w notatce \"Mellis\"."
      PAIRING_CODE=""
      return
      ;;
    *)
      warn "Serwer ${SERVER_URL} nie odpowiada. Aplikację zbuduję, a telefon połączysz później."
      ;;
  esac

  if [ "$SERVER_STATE" = "COMPLETED" ] && [ "$CODE_FROM_FLAG" = "0" ]; then
    # The first phone has connected: the configuration code is void. New phones join by invitation.
    PAIRING_CODE=""
    info "Telefon właściciela jest już połączony. Kolejne telefony łączysz zaproszeniem:"
    info "Mellis → Ustawienia → Udostępnianie → Zaproś osobę."
    return
  fi

  if [ "$CODE_FROM_FLAG" = "0" ]; then
    while true; do
      ask "Kod konfiguracji (Enter = połączę później kodem QR)" "$PAIRING_CODE"
      if [ -z "$REPLY" ]; then PAIRING_CODE=""; info "Bez kodu: aplikacja pokaże ekran łączenia z serwerem."; break; fi
      read_code_answer "$REPLY"; status=$?
      case "$status" in
        0) break ;;
        2) warn "Ten link jest z innego serwera niż ${SERVER_URL}." ;;
        *) warn "Kod konfiguracji wygląda tak: 7KQ2M-9XH4T-3BWRZ-8QJ5N (litery i cyfry, grupy po 5)." ;;
      esac
    done
  fi
  if [ -n "$PAIRING_CODE" ]; then
    classify_code
    ok "kod konfiguracji ${PAIRING_CODE%%-*}-…  (telefon połączy się z serwerem po instalacji)"
  fi
}

