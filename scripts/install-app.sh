# Whether the first phone installed in this run opens the configuration code.
pairing_pending() {
  [ -n "$PAIRING_CODE" ] || return 1
  [ "$SERVER_STATE" != "NOT_DEVICE" ] || return 1
  [ "$SERVER_STATE" != "COMPLETED" ] || [ "$CODE_FROM_FLAG" = "1" ]
}

choose_devices() {
  step "Telefony"
  local count i line default_choice="" last_all=0 choice
  while true; do
    DEVICES_TSV="$(list_devices)" || fail "xcrun devicectl nie odpowiada. Zamknij i otwórz Xcode, potem spróbuj ponownie."
    count="$(printf '%s' "$DEVICES_TSV" | grep -c .)"
    if [ "$count" -gt 0 ]; then break; fi
    no_phone_hint
    if [ "$OPT_NO_INSTALL" = "1" ]; then SELECTED_IDS=""; return; fi
    ask "Enter = sprawdź ponownie, b = tylko zbuduj, bez instalacji" ""
    case "$REPLY" in b|B) SELECTED_IDS=""; return ;; esac
  done

  if printf '%s\n' "$DEVICES_TSV" | cut -f6 | grep -qv '^connected$'; then
    info "${C_DIM}Telefon \"teraz niedostępny\": odblokuj go i połącz z tą samą siecią Wi-Fi co Mac.${C_OFF}"
  fi
  info "${C_DIM}Telefonu nie ma na liście? Podłącz go raz kablem (Zaufaj + Tryb dewelopera) i wybierz r.${C_OFF}"
  if pairing_pending && [ "$count" -gt 1 ]; then
    info "Za pierwszym razem wybierz tylko swój telefon: kod konfiguracji łączy z serwerem jeden telefon."
  fi
  printf '\n'

  if [ "$LAST_DEVICES" = "ALL" ]; then last_all=1; fi
  i=0
  while IFS= read -r line; do
    [ -n "$line" ] || continue
    i=$((i + 1))
    printf '%d) %s\n' "$i" "$(describe_device "$line")"
    if [ "$last_all" = "0" ] && [ -n "$LAST_DEVICES" ] && [ "$(device_field "$line" 1)" = "$LAST_DEVICES" ]; then
      default_choice="$i"
    fi
  done <<EOF
$DEVICES_TSV
EOF
  local all_index=$((count + 1))
  if [ "$count" -gt 1 ]; then printf '%d) Wszystkie z listy\n' "$all_index"; fi
  printf '0) Nie instaluj, tylko zbuduj\n'
  printf 'r) Odśwież listę\n'

  if [ "$last_all" = "1" ] && [ "$count" -gt 1 ]; then default_choice="$all_index"; fi
  if [ -z "$default_choice" ]; then default_choice=1; fi
  if [ "$OPT_NO_INSTALL" = "1" ]; then
    info "Bez instalacji (--no-install / --dry-run): tylko lista."
    SELECTED_IDS=""
    return
  fi

  while true; do
    ask "Na który telefon zainstalować?" "$default_choice" ""
    choice="$REPLY"
    case "$choice" in
      r|R) choose_devices; return ;;
      0) SELECTED_IDS=""; return ;;
    esac
    if printf '%s' "$choice" | grep -Eq '^[0-9]+$'; then
      if [ "$choice" -ge 1 ] && [ "$choice" -le "$count" ]; then
        SELECTED_IDS="$(printf '%s\n' "$DEVICES_TSV" | sed -n "${choice}p" | cut -f1)"
        LAST_DEVICES="$SELECTED_IDS"
        line="$(printf '%s\n' "$DEVICES_TSV" | sed -n "${choice}p")"
        if [ "$(device_field "$line" 6)" = "connected" ] && [ -n "$(device_field "$line" 2)" ]; then
          # One connected phone: build for it, so Xcode registers it in the team's profile if it is new.
          BUILD_DESTINATION="id=$(device_field "$line" 2)"
        fi
        return
      fi
      if [ "$count" -gt 1 ] && [ "$choice" = "$all_index" ]; then
        SELECTED_IDS="$(printf '%s\n' "$DEVICES_TSV" | cut -f1 | tr '\n' ' ')"
        LAST_DEVICES="ALL"
        if pairing_pending; then
          info "Z serwerem połączy się sam tylko pierwszy telefon: $(device_field "$(printf '%s\n' "$DEVICES_TSV" | sed -n 1p)" 3)."
          info "Pozostałe dołączą zaproszeniem (Mellis → Ustawienia → Udostępnianie → Zaproś osobę)."
        fi
        return
      fi
    fi
    warn "Wybierz numer z listy."
  done
}

device_line() { # device_line <identifier>
  printf '%s\n' "$DEVICES_TSV" | awk -F '\t' -v id="$1" '$1 == id'
}

