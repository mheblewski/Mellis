# json_get <dotted.path> < json -> the value (objects and booleans as JSON), exit 1 when missing or null.
json_get() {
  python3 -I -c '
import json, sys
try:
    value = json.load(sys.stdin)
except Exception:
    sys.exit(1)
for key in sys.argv[1].split("."):
    if isinstance(value, dict) and key in value:
        value = value[key]
    else:
        sys.exit(1)
if value is None:
    sys.exit(1)
print(json.dumps(value) if isinstance(value, (dict, list, bool)) else value)
' "$1"
}

