import { existsSync, readFileSync, writeFileSync } from 'fs';
import { execFileSync } from 'child_process';
import { createInterface } from 'node:readline/promises';
import { Writable } from 'stream';
import path from 'path';
import os from 'os';

const rootDir = process.cwd();
const envPath = path.join(rootDir, '.env');
const iosEnvPath = path.join(rootDir, 'apps/ios/.env.local');
const iosPackagePath = path.join(rootDir, 'apps/ios');

interface WizardAnswers {
  databaseUrl: string;
  apiPort: string;
  nightscoutBaseUrl: string;
  nightscoutApiToken: string;
  nightscoutPatientId: string;
  aiProvider: 'fake' | 'openai';
  openAiApiKey: string;
  openAiModel: string;
  openAiTimeoutMs: string;
  pushProvider: 'fake' | 'apns';
  appleTeamId: string;
  iosBundleId: string;
  apnsTeamId: string;
  apnsKeyId: string;
  apnsPrivateKeyPath: string;
  apnsBundleId: string;
  apnsUseSandbox: string;
  apnsTimeoutMs: string;
  apiBaseUrl: string;
  cognitoUserPoolId: string;
  cognitoClientId: string;
  cognitoTokenUse: string;
  bootstrapConversationId: string;
}

function createPrompter(hidden = false) {
  const output = hidden
    ? new Writable({
        write(_chunk, _encoding, callback) {
          callback();
        },
      })
    : process.stdout;

  return createInterface({
    input: process.stdin,
    output,
  });
}

async function prompt(question: string, defaultValue = ''): Promise<string> {
  const rl = createPrompter(false);
  const suffix = defaultValue ? ` [${defaultValue}]` : '';
  const answer = await rl.question(`${question}${suffix}: `);
  rl.close();
  return answer.trim() || defaultValue;
}

async function promptSecret(question: string): Promise<string> {
  const rl = createPrompter(true);
  const answer = await rl.question(`${question}: `);
  rl.close();
  return answer.trim();
}

async function promptYesNo(question: string, defaultYes = false): Promise<boolean> {
  const defaultLabel = defaultYes ? 'Y/n' : 'y/N';
  const answer = await prompt(`${question} (${defaultLabel})`, defaultYes ? 'y' : 'n');
  return ['y', 'yes', 'true', '1'].includes(answer.toLowerCase());
}

function detectLanIp(): string {
  const interfaces = ['en0', 'en1'];
  for (const networkInterface of interfaces) {
    try {
      const result = execFileSync('ipconfig', ['getifaddr', networkInterface], { encoding: 'utf8' }).trim();
      if (result) {
        return result;
      }
    } catch {
      // Try next interface.
    }
  }

  return '';
}

function parseSimpleEnv(content: string): Map<string, string> {
  const map = new Map<string, string>();
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }

    const match = /^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/.exec(line);
    if (!match) {
      continue;
    }

    map.set(match[1], match[2]);
  }
  return map;
}

function formatEnvValue(value: string): string {
  if (value.includes('\n')) {
    return JSON.stringify(value);
  }

  if (/\s/.test(value) || value.includes('#') || value.includes('=') || value.includes('"')) {
    return JSON.stringify(value);
  }

  return value;
}

function mergeEnvFile(filePath: string, entries: Record<string, string>): void {
  const existing = existsSync(filePath) ? parseSimpleEnv(readFileSync(filePath, 'utf8')) : new Map<string, string>();
  const merged = new Map(existing);
  for (const [key, value] of Object.entries(entries)) {
    merged.set(key, value);
  }

  const lines = [
    '# Generated by npm run setup:iphone',
    ...Array.from(merged.entries()).map(([key, value]) => `${key}=${formatEnvValue(value)}`),
  ];

  writeFileSync(filePath, `${lines.join('\n')}\n`, 'utf8');
}

function readEnvIfPresent(filePath: string): Map<string, string> {
  return existsSync(filePath) ? parseSimpleEnv(readFileSync(filePath, 'utf8')) : new Map<string, string>();
}

function defaultValueFrom(sources: Array<Map<string, string>>, key: string, fallback = ''): string {
  for (const source of sources) {
    const value = source.get(key);
    if (value && value.trim()) {
      return value;
    }
  }

  return fallback;
}

function setLaunchdEnv(entries: Record<string, string>): void {
  for (const [key, value] of Object.entries(entries)) {
    execFileSync('launchctl', ['setenv', key, value], { stdio: 'ignore' });
  }
}

async function main(): Promise<void> {
  const args = new Set(process.argv.slice(2));
  if (args.has('--help') || args.has('-h')) {
    console.log('Usage: tsx scripts/setup-physical-iphone.ts [--dry-run]');
    console.log('Prompts for local backend, worker, OpenAI, APNs, and iPhone development values, then writes .env files and opens Xcode.');
    return;
  }

  const dryRun = args.has('--dry-run');
  const detectedLanIp = detectLanIp();
  const apiBaseUrlDefault = detectedLanIp ? `http://${detectedLanIp}:3001` : 'http://<MAC-LAN-IP>:3001';
  const backendDefaults = readEnvIfPresent(envPath);
  const iosDefaults = readEnvIfPresent(iosEnvPath);
  const defaults = [iosDefaults, backendDefaults];

  console.log('GlucoMind physical iPhone setup wizard');
  console.log('Type secrets directly in the terminal when asked. They are only written to local ignored files.');

  if (dryRun) {
    console.log('Dry run mode: no prompts, no files will be written, and Xcode will not be opened.');
    console.log(`Recommended API_BASE_URL: ${apiBaseUrlDefault}`);
    console.log('Recommended Apple Team ID: your Apple Developer Team ID');
    console.log('Recommended iOS bundle id: pl.glucomind.ios');
    console.log('Recommended APNs key path: ~/Library/Application Support/GlucoMind/APNs/AuthKey_XXXXXX.p8');
    console.log('You still need to enable Push Notifications and Associated Domains in Xcode for the app target.');
    return;
  }

  const answers: WizardAnswers = {
    databaseUrl: await prompt('DATABASE_URL', defaultValueFrom(defaults, 'DATABASE_URL', 'postgresql://postgres:postgres@localhost:5432/gluco_mind')),
    apiPort: await prompt('API_PORT', defaultValueFrom(defaults, 'API_PORT', '3001')),
    nightscoutBaseUrl: await prompt('NIGHTSCOUT_BASE_URL', defaultValueFrom(defaults, 'NIGHTSCOUT_BASE_URL', 'https://nightscout.example.com')),
    nightscoutApiToken: defaultValueFrom(defaults, 'NIGHTSCOUT_API_TOKEN') || await promptSecret('NIGHTSCOUT_API_TOKEN'),
    nightscoutPatientId: await prompt('NIGHTSCOUT_PATIENT_ID', defaultValueFrom(defaults, 'NIGHTSCOUT_PATIENT_ID', 'patient-1')),
    aiProvider: (await prompt('AI_PROVIDER (fake/openai)', defaultValueFrom(defaults, 'AI_PROVIDER', 'fake'))) === 'openai' ? 'openai' : 'fake',
    openAiApiKey: defaultValueFrom(defaults, 'OPENAI_API_KEY'),
    openAiModel: await prompt('OPENAI_MODEL', defaultValueFrom(defaults, 'OPENAI_MODEL', 'gpt-5.6-terra')),
    openAiTimeoutMs: await prompt('OPENAI_TIMEOUT_MS', defaultValueFrom(defaults, 'OPENAI_TIMEOUT_MS', '15000')),
    pushProvider: (await prompt('PUSH_PROVIDER (fake/apns)', defaultValueFrom(defaults, 'PUSH_PROVIDER', 'fake'))) === 'apns' ? 'apns' : 'fake',
    appleTeamId: await prompt('APPLE_TEAM_ID', defaultValueFrom(defaults, 'APPLE_TEAM_ID', '')),
    iosBundleId: await prompt('IOS_BUNDLE_ID', defaultValueFrom(defaults, 'IOS_BUNDLE_ID', 'pl.glucomind.ios')),
    apnsTeamId: defaultValueFrom(defaults, 'APNS_TEAM_ID'),
    apnsKeyId: defaultValueFrom(defaults, 'APNS_KEY_ID'),
    apnsPrivateKeyPath: defaultValueFrom(defaults, 'APNS_PRIVATE_KEY_PATH'),
    apnsBundleId: defaultValueFrom(defaults, 'APNS_BUNDLE_ID'),
    apnsUseSandbox: (await prompt('APNS_USE_SANDBOX', defaultValueFrom(defaults, 'APNS_USE_SANDBOX', 'true'))).toLowerCase() === 'false' ? 'false' : 'true',
    apnsTimeoutMs: await prompt('APNS_TIMEOUT_MS', defaultValueFrom(defaults, 'APNS_TIMEOUT_MS', '10000')),
    apiBaseUrl: await prompt('API_BASE_URL', defaultValueFrom(defaults, 'API_BASE_URL', apiBaseUrlDefault)),
    cognitoUserPoolId: await prompt('COGNITO_USER_POOL_ID', defaultValueFrom(defaults, 'COGNITO_USER_POOL_ID', 'eu-central-1_example')),
    cognitoClientId: await prompt('COGNITO_CLIENT_ID', defaultValueFrom(defaults, 'COGNITO_CLIENT_ID', 'example-client-id')),
    cognitoTokenUse: (await prompt('COGNITO_TOKEN_USE (access/id)', defaultValueFrom(defaults, 'COGNITO_TOKEN_USE', 'access'))).toLowerCase() === 'id' ? 'id' : 'access',
    bootstrapConversationId: await prompt('GLUCOMIND_BOOTSTRAP_CONVERSATION_ID', defaultValueFrom(defaults, 'GLUCOMIND_BOOTSTRAP_CONVERSATION_ID', '')),
  };

  if (answers.aiProvider === 'openai') {
    answers.openAiApiKey = answers.openAiApiKey || await promptSecret('OPENAI_API_KEY');
  }

  if (answers.pushProvider === 'apns') {
    answers.apnsTeamId = answers.apnsTeamId || await prompt('APNS_TEAM_ID', '');
    answers.apnsKeyId = answers.apnsKeyId || await prompt('APNS_KEY_ID', '');
    answers.apnsPrivateKeyPath = answers.apnsPrivateKeyPath || await prompt('APNS_PRIVATE_KEY_PATH', `${os.homedir()}/Library/Application Support/GlucoMind/APNs/AuthKey_XXXXXX.p8`);
    answers.apnsBundleId = answers.apnsBundleId || answers.iosBundleId;
  }

  const backendEnv: Record<string, string> = {
    DATABASE_URL: answers.databaseUrl,
    API_PORT: answers.apiPort,
    NIGHTSCOUT_BASE_URL: answers.nightscoutBaseUrl,
    NIGHTSCOUT_API_TOKEN: answers.nightscoutApiToken,
    NIGHTSCOUT_PATIENT_ID: answers.nightscoutPatientId,
    AI_PROVIDER: answers.aiProvider,
    OPENAI_API_KEY: answers.openAiApiKey,
    OPENAI_MODEL: answers.openAiModel,
    OPENAI_TIMEOUT_MS: answers.openAiTimeoutMs,
    PUSH_PROVIDER: answers.pushProvider,
    APPLE_TEAM_ID: answers.appleTeamId,
    IOS_BUNDLE_ID: answers.iosBundleId,
    APNS_TEAM_ID: answers.apnsTeamId,
    APNS_KEY_ID: answers.apnsKeyId,
    APNS_PRIVATE_KEY_PATH: answers.apnsPrivateKeyPath,
    APNS_BUNDLE_ID: answers.apnsBundleId,
    APNS_USE_SANDBOX: answers.apnsUseSandbox,
    APNS_TIMEOUT_MS: answers.apnsTimeoutMs,
  };

  const iosEnv: Record<string, string> = {
    API_BASE_URL: answers.apiBaseUrl,
    GLUCOMIND_API_BASE_URL: answers.apiBaseUrl,
    COGNITO_USER_POOL_ID: answers.cognitoUserPoolId,
    COGNITO_CLIENT_ID: answers.cognitoClientId,
    COGNITO_TOKEN_USE: answers.cognitoTokenUse,
    GLUCOMIND_BOOTSTRAP_CONVERSATION_ID: answers.bootstrapConversationId,
    IOS_BUNDLE_ID: answers.iosBundleId,
    APPLE_TEAM_ID: answers.appleTeamId,
  };

  if (dryRun) {
    console.log('Dry run complete. No files written.');
    console.log('Backend env keys:', Object.keys(backendEnv).join(', '));
    console.log('iOS env keys:', Object.keys(iosEnv).join(', '));
    return;
  }

  mergeEnvFile(envPath, backendEnv);
  mergeEnvFile(iosEnvPath, iosEnv);
  setLaunchdEnv(iosEnv);

  console.log(`Wrote ${envPath}`);
  console.log(`Wrote ${iosEnvPath}`);
  console.log('Opened GUI environment for the iOS app. If Xcode was already open, quit and relaunch it to pick up the environment.');

  execFileSync('/usr/bin/open', ['-a', 'Xcode', iosPackagePath], { stdio: 'ignore' });
  console.log('Xcode opened on apps/ios. Select a physical iPhone and build/run.');
  console.log('In Xcode, enable Push Notifications and Associated Domains for the app target, then confirm the signing team and bundle identifier.');
}

void main().catch((error: unknown) => {
  const message = error instanceof Error ? error.message : String(error);
  console.error(message);
  process.exitCode = 1;
});
