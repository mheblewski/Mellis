# Physical iPhones / iPads paired with this Mac, one per line:
# identifier<TAB>udid<TAB>name<TAB>iOS<TAB>transport<TAB>state<TAB>developer mode
list_devices() {
  local json status=0
  json="$(mktemp "${TMPDIR:-/tmp}/mellis-devices.XXXXXX")"
  if ! xcrun devicectl list devices --json-output "$json" >/dev/null 2>&1; then
    rm -f "$json"
    return 1
  fi
  python3 -I -c '
import json, sys
def pick(device, *paths):
    for path in paths:
        value = device
        for key in path.split("."):
            value = value.get(key) if isinstance(value, dict) else None
        if value not in (None, ""):
            return value
    return ""
try:
    devices = json.load(open(sys.argv[1]))["result"]["devices"]
except Exception:
    sys.exit(1)
for d in devices:
    platform = pick(d, "hardwareProperties.platform", "properties.hardware.platform")
    kind = pick(d, "hardwareProperties.deviceType", "properties.hardware.deviceType")
    reality = pick(d, "hardwareProperties.reality", "properties.hardware.reality")
    if platform != "iOS" or reality == "simulated" or kind not in ("iPhone", "iPad"):
        continue
    devmode = pick(d, "deviceProperties.developerModeStatus", "properties.state.developerModeStatus")
    if isinstance(devmode, dict):
        devmode = next(iter(devmode), "")
    row = [
        pick(d, "identifier"),
        pick(d, "hardwareProperties.udid", "properties.hardware.udid"),
        str(pick(d, "deviceProperties.name", "properties.state.name") or "?").strip(),
        str(pick(d, "deviceProperties.osVersionNumber", "properties.software.osVersionNumber.stringValue") or "?"),
        pick(d, "connectionProperties.transportType", "properties.connection.transportType"),
        pick(d, "connectionProperties.tunnelState", "properties.connection.state"),
        str(devmode),
    ]
    print("\t".join(str(v).replace("\t", " ") for v in row))
' "$json" || status=1
  rm -f "$json"
  return "$status"
}

device_field() { # device_field <line> <column>
  printf '%s\n' "$1" | cut -f"$2"
}

describe_device() {
  local line="$1" transport state devmode connection status
  transport="$(device_field "$line" 5)"; state="$(device_field "$line" 6)"; devmode="$(device_field "$line" 7)"
  case "$transport" in
    wired) connection="kabel" ;;
    localNetwork|network) connection="Wi-Fi" ;;
    *) connection="$transport" ;;
  esac
  if [ "$state" = "connected" ]; then status="połączony"; else status="teraz niedostępny"; fi
  # An unreachable phone may come without a transport: then only its state.
  printf '%s · iOS %s · %s%s' "$(device_field "$line" 3)" "$(device_field "$line" 4)" "${connection:+$connection · }" "$status"
  if [ "$devmode" = "disabled" ]; then printf ' · wyłączony Tryb dewelopera'; fi
}

