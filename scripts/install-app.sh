install_on() {
  local id="$1" name log
  name="$(device_name "$id")"
  log="${STATE_DIR}/install-${id}.log"
  info "→ ${name}: instaluję…"
  if ! xcrun devicectl device install app --device "$id" --timeout 180 "$BUILT_APP" >"$log" 2>&1; then
    if grep -Eqi 'not connected|unavailable|could not connect|timed out|timeout|locked|unreachable' "$log"; then
      add_result "✗ ${name}: niedostępny. Odblokuj telefon, ta sama sieć Wi-Fi co Mac (albo kabel), i uruchom ponownie."
    elif grep -Eqi 'developer mode' "$log"; then
      add_result "✗ ${name}: włącz Tryb dewelopera (Ustawienia → Prywatność i ochrona → Tryb dewelopera)."
    elif grep -Eqi 'provision|not included|profile' "$log"; then
      add_result "✗ ${name}: telefonu nie ma w profilu konta. Podłącz go i uruchom skrypt tylko dla niego."
    else
      add_result "✗ ${name}: instalacja nie powiodła się (${log})."
    fi
    warn "${name}: nie udało się"
    return 1
  fi
  INSTALLED_IDS="${INSTALLED_IDS}${id} "
  if [ "$id" = "$PAIR_DEVICE_ID" ]; then
    add_result "✓ ${name}: zainstalowano"
  elif [ "$LAUNCH_AFTER_INSTALL" = "yes" ]; then
    if xcrun devicectl device process launch --device "$id" --terminate-existing "$BUNDLE_ID" >>"$log" 2>&1; then
      add_result "✓ ${name}: zainstalowano i uruchomiono"
    else
      add_result "✓ ${name}: zainstalowano (uruchom ręcznie; telefon był zablokowany?)"
    fi
  else
    add_result "✓ ${name}: zainstalowano"
  fi
  ok "${name}: gotowe"
}

install_all() {
  local id first="" count=0
  for id in $SELECTED_IDS; do
    if [ -z "$first" ]; then first="$id"; fi
    count=$((count + 1))
  done
  # Only the first phone connects with the configuration code (it works once); the others join by invitation.
  if pairing_pending; then PAIR_DEVICE_ID="$first"; fi
  # The phone that connects is opened anyway; ask about the others.
  if [ -z "$LAUNCH_AFTER_INSTALL" ] && { [ -z "$PAIR_DEVICE_ID" ] || [ "$count" -gt 1 ]; }; then
    if confirm "Uruchomić aplikację na telefonie po instalacji?" Y; then LAUNCH_AFTER_INSTALL="yes"; else LAUNCH_AFTER_INSTALL="no"; fi
  fi
  step "Instaluję"
  mkdir -p "$STATE_DIR"
  for id in $SELECTED_IDS; do
    install_on "$id" || true
  done
}

