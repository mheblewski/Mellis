parse_args() {
  while [ $# -gt 0 ]; do
    case "$1" in
      --server) [ $# -ge 2 ] || fail "--server wymaga adresu"; OPT_SERVER="$2"; shift ;;
      --server=*) OPT_SERVER="${1#--server=}" ;;
      --code) [ $# -ge 2 ] || fail "--code wymaga kodu"; OPT_CODE="$2"; shift ;;
      --code=*) OPT_CODE="${1#--code=}" ;;
      --dir) [ $# -ge 2 ] || fail "--dir wymaga katalogu"; OPT_DIR="$2"; shift ;;
      --dir=*) OPT_DIR="${1#--dir=}" ;;
      --ref) [ $# -ge 2 ] || fail "--ref wymaga nazwy"; OPT_REF="$2"; shift ;;
      --ref=*) OPT_REF="${1#--ref=}" ;;
      --repo) [ $# -ge 2 ] || fail "--repo wymaga adresu"; OPT_REPO="$2"; shift ;;
      --repo=*) OPT_REPO="${1#--repo=}" ;;
      --no-update) OPT_NO_UPDATE=1 ;;
      --debug) OPT_CONFIGURATION="Debug" ;;
      --no-install) OPT_NO_INSTALL=1 ;;
      --dry-run) OPT_DRY_RUN=1; OPT_NO_INSTALL=1 ;;
      -h|--help) usage; exit 0 ;;
      *) fail "nieznana opcja: $1 (zobacz --help)" ;;
    esac
    shift
  done
}

