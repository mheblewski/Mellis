#!/bin/bash
# Mellis: build the iOS app on this Mac, install it on the family's iPhones and connect the owner's phone to the server,
# without clicking in Xcode.
#
#   /bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/mheblewski/Mellis/v1.0.4/scripts/install-app.sh)"
#
# Builds device mode (self-hosted Mellis, pairing instead of accounts: docs/device-auth-api.md): the app gets
# its server from the pairing link, never from the build. Asks for the server address and the configuration code that
# the server installer printed, builds the release that matches the server, installs it and opens the pairing link on
# the first phone (devicectl --payload-url, the app's mellis:// URL scheme).
#
# Asks step by step (in Polish), remembers the answers in ~/.mellis/install-app.env (no keys; the configuration code
# only until the phone has connected) and keeps apps/ios/Config.local.xcconfig, so a rerun only updates the code,
# rebuilds and reinstalls (the yearly rebuild). macOS bash 3.2 compatible, no jq (python3 comes with Xcode).
# Before anything is built the person types "tak" to accept that Mellis is a DIY project, not a medical device
# (accept_diy). MELLIS_ACCEPT_DIY=tak accepts it ahead; without it the question is asked, and no answer (no terminal,
# end of input) stops the script: it is never accepted silently.
# Run with --help for the options.

