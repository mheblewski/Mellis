# The configuration code as a pairing link -> PAIRING_URL. A pairing code goes into the link as it is; the server's
# SETUP_CODE is exchanged for a fresh 10-minute owner pairing code (POST /v1/setup/owner) right before the link opens.
make_pairing_url() {
  local answer body recovery
  PAIRING_URL=""
  if [ "$CODE_KIND" != "setup" ]; then
    PAIRING_URL="$(python3 -I -c 'import sys, urllib.parse; print("mellis://pair?" + urllib.parse.urlencode({"server": sys.argv[1], "code": sys.argv[2]}))' \
      "$SERVER_URL" "$PAIRING_CODE")"
    return
  fi
  while true; do
    ask "Twoje imię (właściciel, widzą je inni opiekunowie)" "$OWNER_NAME"
    if [ -n "$REPLY" ]; then break; fi
  done
  OWNER_NAME="$REPLY"
  body="$(python3 -I -c 'import json, sys; print(json.dumps({"first_name": sys.argv[1]}))' "$OWNER_NAME")"
  curl_json POST "${SERVER_URL}/v1/setup/owner" "$body" "$PAIRING_CODE"; answer="$HTTP_BODY"
  case "$HTTP_STATUS" in
    201|200) ;;
    409)
      if printf '%s' "$answer" | grep -q SETUP_NEEDS_PATIENT; then
        warn "Na serwerze nie ma jeszcze podopiecznego: dokończ instalację serwera."
      else
        warn "Serwer ma już połączony telefon właściciela."
      fi
      return 1 ;;
    401) warn "Serwer nie przyjął kodu konfiguracji."; return 1 ;;
    503)
      if printf '%s' "$answer" | grep -q PUBLIC_BASE_URL_MISSING; then
        warn "Serwer nie zna swojego adresu: na serwerze uruchom mellis → Zmień ustawienia → Domena / adres serwera."
      else
        warn "Serwer nie odpowiedział (HTTP ${HTTP_STATUS})."
      fi
      return 1 ;;
    *) warn "Serwer nie odpowiedział (HTTP ${HTTP_STATUS})."; return 1 ;;
  esac
  PAIRING_URL="$(printf '%s' "$answer" | json_get pairing.pairing_url)" || return 1
  recovery="$(printf '%s' "$answer" | json_get recovery_code || true)"
  if [ -n "$recovery" ]; then
    printf '\n'
    info "${C_BOLD}Zapisz w notatce \"Mellis\":${C_OFF}"
    info "  Kod odzyskiwania:   ${recovery}   (na wypadek zgubienia wszystkich telefonów)"
    info "Jeśli w notatce był już kod odzyskiwania, przestał działać: zostaw tylko ten."
    printf '\n'
  fi
}

# Opens the pairing link on the phone: the app shows the server's address and connects after "Połącz".
open_pairing_link() {
  local id="$1" url="$2" name log
  name="$(device_name "$id")"
  log="${STATE_DIR}/install-${id}.log"
  while true; do
    if xcrun devicectl device process launch --device "$id" --terminate-existing --payload-url "$url" "$BUNDLE_ID" >>"$log" 2>&1; then
      return 0
    fi
    if grep -Eqi 'trust|untrusted|invalid code signature' "$log"; then
      warn "${name}: iPhone nie ufa jeszcze Twojemu kontu deweloperskiemu."
      info "Na telefonie: Ustawienia → Ogólne → VPN i urządzenia → Twoje konto → Zaufaj."
    else
      warn "${name}: nie udało się otworzyć aplikacji Mellis (telefon zablokowany?)."
    fi
    ask "Odblokuj telefon i naciśnij Enter, albo p = pomiń" ""
    case "$REPLY" in p|P) return 1 ;; esac
  done
}

# Waits until GET /v1/setup says COMPLETED: the owner's phone has connected (setup codes and pairings of the setup).
wait_for_owner_phone() {
  local waited=0 state
  while [ "$waited" -lt "$PAIR_WAIT_SECONDS" ]; do
    curl_json GET "${SERVER_URL}/v1/setup"
    state="$(printf '%s' "$HTTP_BODY" | json_get setup || true)"
    if [ "$state" = "COMPLETED" ]; then printf '\n'; return 0; fi
    printf '.'
    sleep "$PAIR_POLL_SECONDS"
    waited=$((waited + (PAIR_POLL_SECONDS > 0 ? PAIR_POLL_SECONDS : 1)))
  done
  printf '\n'
  return 1
}

pair_first_phone() {
  local id="$PAIR_DEVICE_ID" name other others=""
  [ -n "$id" ] || return 0
  name="$(device_name "$id")"
  step "Łączę ${name} z serwerem"
  case " $INSTALLED_IDS " in
    *" $id "*) ;;
    *)
      add_result "! ${name}: bez połączenia z serwerem (instalacja nie wyszła). Kod konfiguracji czeka na następne uruchomienie."
      return 0 ;;
  esac
  if [ "$SERVER_STATE" = "UNREACHABLE" ]; then
    # Not answering before the build: ask again now (and whether the code is the server's setup code).
    check_server
    if [ "$SERVER_STATE" = "COMPLETED" ] && [ "$CODE_FROM_FLAG" = "0" ]; then
      PAIRING_CODE=""
      add_result "✓ ${name}: telefon właściciela jest już połączony z serwerem"
      return 0
    fi
    classify_code
  fi
  if ! make_pairing_url; then
    add_result "! ${name}: nie połączono z serwerem. Na serwerze: mellis → Połącz telefon właściciela."
    return 0
  fi
  save_state
  if ! open_pairing_link "$id" "$PAIRING_URL"; then
    add_result "! ${name}: otwórz aplikację Mellis i połącz telefon kodem QR (na serwerze: mellis → Połącz telefon właściciela)."
    return 0
  fi
  info "Na telefonie ${name} otworzył się Mellis z adresem Twojego serwera: stuknij ${C_BOLD}Połącz${C_OFF}."
  if [ "$SERVER_STATE" = "COMPLETED" ]; then
    # A pairing code of an already set up server (mellis reset-owner): the server's setup state does not change.
    PAIRING_CODE=""
    add_result "✓ ${name}: otwarto link łączenia z serwerem (stuknij Połącz na telefonie)"
    return 0
  fi
  printf '    Czekam na połączenie'
  if wait_for_owner_phone; then
    PAIRING_CODE=""
    SERVER_STATE="COMPLETED"
    ok "${name}: połączony z serwerem (właściciel)"
    add_result "✓ ${name}: połączony z serwerem jako właściciel"
  else
    warn "Telefon jeszcze się nie połączył."
    info "Jeśli aplikacja pisze, że kod jest nieważny (działa 10 minut): na serwerze wpisz mellis →"
    info "Połącz telefon właściciela i zeskanuj kod QR w aplikacji."
    add_result "! ${name}: nie widzę połączenia z serwerem. Zobacz ekran telefonu."
  fi
  for other in $INSTALLED_IDS; do
    [ "$other" = "$id" ] || others="${others}$(device_name "$other"), "
  done
  if [ -n "$others" ]; then
    add_result "  Pozostałe telefony (${others%, }) dołączą zaproszeniem: Mellis → Ustawienia → Udostępnianie → Zaproś osobę."
  fi
}

