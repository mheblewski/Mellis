# Clones or fetches the repository; the version is checked out after the server question (choose_version).
prepare_repo() {
  step "Kod aplikacji"
  MELLIS_DIR="${OPT_DIR:-${MELLIS_DIR:-${HOME}/Mellis}}"
  MELLIS_REPO="${OPT_REPO:-${MELLIS_REPO:-$DEFAULT_REPO_URL}}"
  case "$MELLIS_DIR" in "~"/*) MELLIS_DIR="${HOME}/${MELLIS_DIR#\~/}" ;; esac
  WORK_DIR="$MELLIS_DIR"

  if [ -d "${WORK_DIR}/.git" ]; then
    ok "katalog ${WORK_DIR}"
    if [ "$OPT_NO_UPDATE" = "1" ]; then
      info "Bez pobierania nowego kodu (--no-update): $(git -C "$WORK_DIR" log -1 --format='%h %s')"
      return
    fi
    info "Pobieram nowy kod"
    git -C "$WORK_DIR" remote set-url origin "$MELLIS_REPO"
    git -C "$WORK_DIR" fetch --quiet --tags --prune --force origin || fail "nie udało się pobrać zmian (internet?)."
  elif [ -e "$WORK_DIR" ] && [ -n "$(ls -A "$WORK_DIR" 2>/dev/null)" ]; then
    fail "${WORK_DIR} istnieje i nie jest kopią repozytorium Mellis. Wybierz inny katalog: --dir KATALOG"
  else
    info "Pobieram ${MELLIS_REPO} do ${WORK_DIR}"
    git clone --quiet "$MELLIS_REPO" "$WORK_DIR" || fail "nie udało się pobrać repozytorium."
  fi
  ok "kod pobrany"
}

# The newest release tag (vX.Y.Z, no pre-releases), empty when the repository has none.
latest_release_tag() {
  git -C "$WORK_DIR" tag -l 'v[0-9]*' --sort=-v:refname 2>/dev/null | grep -E '^v[0-9]+\.[0-9]+\.[0-9]+$' | head -1
}

# The ref to build: --ref, else the release of the server's version (v<server.version>), else the newest release,
# else the default branch. Prints it; warnings go to stderr.
pick_ref() {
  local tag
  if [ -n "$OPT_REF" ]; then printf '%s\n' "$OPT_REF"; return; fi
  if [ -n "$SERVER_VERSION" ]; then
    tag="v${SERVER_VERSION#v}"
    if git -C "$WORK_DIR" rev-parse --verify --quiet "refs/tags/${tag}^{commit}" >/dev/null; then
      printf '%s\n' "$tag"; return
    fi
    warn "W repozytorium nie ma wydania ${tag} (wersja serwera)." >&2
  fi
  tag="$(latest_release_tag)"
  if [ -n "$tag" ]; then printf '%s\n' "$tag"; return; fi
  tag="$(git -C "$WORK_DIR" symbolic-ref --short refs/remotes/origin/HEAD 2>/dev/null | sed 's#^origin/##')"
  printf '%s\n' "${tag:-main}"
}

choose_version() {
  step "Wersja aplikacji"
  if [ "$OPT_NO_UPDATE" = "1" ]; then
    info "Bez zmiany wersji (--no-update): $(git -C "$WORK_DIR" describe --tags --always 2>/dev/null)"
    return
  fi
  local ref target dirty
  ref="$(pick_ref)"
  if [ -n "$OPT_REF" ]; then
    info "Wersja z --ref: ${ref}"
  elif [ -n "$SERVER_VERSION" ] && [ "$ref" = "v${SERVER_VERSION#v}" ]; then
    info "Zgodna z serwerem (${SERVER_VERSION})."
  elif [ -n "$SERVER_VERSION" ]; then
    warn "Buduję ${ref}; serwer ma wersję ${SERVER_VERSION}."
  else
    info "Serwer nie podał wersji: buduję ${ref}."
  fi

  if git -C "$WORK_DIR" rev-parse --verify --quiet "refs/remotes/origin/${ref}^{commit}" >/dev/null; then
    target="origin/${ref}"
  elif git -C "$WORK_DIR" rev-parse --verify --quiet "refs/tags/${ref}^{commit}" >/dev/null; then
    target="refs/tags/${ref}"
  elif git -C "$WORK_DIR" rev-parse --verify --quiet "${ref}^{commit}" >/dev/null; then
    target="$ref"
  else
    fail "nie znam wersji \"${ref}\" (tag, gałąź albo commit)."
  fi

  # XcodeGen rewrites the generated project and Info.plist files; anything else is a change of the user's own.
  dirty="$(git -C "$WORK_DIR" status --porcelain --untracked-files=no -- . \
    ':(exclude)apps/ios/GlucoMindiOS.xcodeproj' ':(exclude)apps/ios/Sources/*/Info.plist')"
  if [ -n "$dirty" ]; then
    warn "W ${WORK_DIR} są zmienione pliki:"
    printf '%s\n' "$dirty" | sed 's/^/        /'
    if ! confirm "Odrzucić te zmiany i przełączyć na ${ref}? (Config.local.xcconfig zostaje)" N; then
      info "Buduję bez zmiany wersji."
      return
    fi
  fi
  # A detached checkout of the exact ref: the managed copy never carries local commits.
  git -C "$WORK_DIR" checkout --quiet --force --detach "$target" || fail "nie udało się przełączyć na ${ref}."
  ok "wersja ${ref} · $(git -C "$WORK_DIR" log -1 --format='%h %s')"
}

# ---------- 3. Apple team ----------

# Teams of the Apple accounts signed in to Xcode (Settings → Accounts), as "TEAMID<TAB>name<TAB>type" lines; with
# "free" as the argument, prints "free" when only free (Personal Team) teams are there.
# Xcode 15-27 keep them in IDEProvisioningTeamByIdentifier (older ones in IDEProvisioningTeams).
xcode_teams() {
  defaults export com.apple.dt.Xcode - 2>/dev/null | python3 -I -c '
import plistlib, sys
try:
    prefs = plistlib.loads(sys.stdin.buffer.read())
except Exception:
    sys.exit(0)
teams = []
for key in ("IDEProvisioningTeamByIdentifier", "IDEProvisioningTeams"):
    groups = prefs.get(key)
    if isinstance(groups, dict):
        for group in groups.values():
            if isinstance(group, list):
                teams.extend(t for t in group if isinstance(t, dict) and t.get("teamID"))
        break
paid, seen = [], set()
for team in teams:
    if team.get("isFreeProvisioningTeam") or team["teamID"] in seen:
        continue
    seen.add(team["teamID"])
    paid.append(team)
if len(sys.argv) > 1 and sys.argv[1] == "free":
    if not paid and teams:
        print("free")
    sys.exit(0)
for team in sorted(paid, key=lambda t: t["teamID"]):
    print("\t".join([team["teamID"], str(team.get("teamName") or "?"), str(team.get("teamType") or "")]))
' "$@"
}

valid_team_id() {
  printf '%s' "$1" | grep -Eq '^[A-Z0-9]{10}$'
}

choose_team() {
  step "Konto Apple Developer (Team ID)"
  local teams count i id name type default_index=1
  while true; do
    teams="$(xcode_teams)"
    if [ -n "$teams" ]; then break; fi
    if [ "$(xcode_teams free)" = "free" ]; then
      warn "W Xcode jest tylko darmowe konto (Personal Team). Mellis potrzebuje płatnego Apple Developer"
      warn "(powiadomienia, widżet), tak jak Trio i Loop."
    else
      warn "W Xcode nie jest zalogowane żadne konto Apple."
    fi
    info "Otwórz Xcode → Settings… → Accounts → + → Apple ID i zaloguj się kontem Apple Developer."
    if [ -n "$TEAM_ID" ]; then
      info "Albo zostaw zapamiętany Team ID ${TEAM_ID} (budowanie i tak wymaga zalogowanego konta)."
    fi
    ask "Enter = sprawdź ponownie, albo wpisz Team ID ręcznie (10 znaków)" ""
    if [ -n "$REPLY" ]; then
      REPLY="$(printf '%s' "$REPLY" | tr '[:lower:]' '[:upper:]')"
      if valid_team_id "$REPLY"; then TEAM_ID="$REPLY"; ok "Team ID ${TEAM_ID}"; return; fi
      warn "Team ID to 10 liter i cyfr, np. AB12CD34EF (developer.apple.com → Account → Membership)."
    fi
  done

  count="$(printf '%s\n' "$teams" | grep -c .)"
  i=0
  while IFS="$(printf '\t')" read -r id name type; do
    i=$((i + 1))
    if [ "$id" = "$TEAM_ID" ]; then default_index=$i; fi
  done <<EOF
$teams
EOF

  if [ "$count" = "1" ]; then
    IFS="$(printf '\t')" read -r id name type <<EOF
$teams
EOF
    if confirm "Budować z kontem ${name} (Team ID ${id})?" Y; then
      TEAM_ID="$id"; ok "Team ID ${TEAM_ID}"; return
    fi
    ask "Team ID (10 znaków, developer.apple.com → Account → Membership)" ""
  else
    info "Konta w Xcode:"
    i=0
    while IFS="$(printf '\t')" read -r id name type; do
      i=$((i + 1))
      printf '      %d) %s · %s%s\n' "$i" "$name" "$id" "${type:+ · $type}"
    done <<EOF
$teams
EOF
    ask "Które konto? (numer albo inny Team ID)" "$default_index"
  fi

  while true; do
    if printf '%s' "$REPLY" | grep -Eq '^[0-9]+$' && [ "$REPLY" -ge 1 ] && [ "$REPLY" -le "$count" ]; then
      TEAM_ID="$(printf '%s\n' "$teams" | sed -n "${REPLY}p" | cut -f1)"
      break
    fi
    REPLY="$(printf '%s' "$REPLY" | tr '[:lower:]' '[:upper:]')"
    if valid_team_id "$REPLY"; then TEAM_ID="$REPLY"; break; fi
    warn "Wpisz numer z listy albo Team ID (10 liter i cyfr, np. AB12CD34EF)."
    ask "Team ID" ""
  done
  ok "Team ID ${TEAM_ID}"
}

